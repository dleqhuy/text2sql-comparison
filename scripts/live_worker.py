"""Observe original method implementations in isolated subprocesses.

Only public model responses, prompts and tool audits are recorded. No synthetic
steps or private model reasoning are generated by this adapter.
"""

import argparse
import asyncio
import functools
import importlib.util
import json
import os
import sys
import time
import traceback
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WORKSPACE = ROOT.parent
OUTPUT = None
METHOD = None


def emit(kind, stage, **data):
    record = dict(time=time.time(), method=METHOD, kind=kind, stage=stage, **data)
    line = json.dumps(record, ensure_ascii=False, default=str)
    # SDK/provider exceptions can contain request details. Never persist secrets.
    for name in ("LLM_API_KEY", "OPENAI_API_KEY", "CODEX_API_KEY"):
        secret = os.environ.get(name)
        if secret:
            line = line.replace(secret, "[REDACTED]")
    with (OUTPUT / "events.jsonl").open("a", encoding="utf-8") as stream:
        stream.write(line + "\n")


def observed(stage, function, *args, **kwargs):
    started = time.monotonic()
    emit("start", stage, input=args[0] if args else kwargs)
    try:
        answer = function(*args, **kwargs)
    except Exception as error:
        emit("error", stage, output=str(error), elapsed=time.monotonic() - started)
        raise
    emit("finish", stage, output=answer, elapsed=time.monotonic() - started)
    return answer


def din(row, source):
    repo = WORKSPACE / "Few-shot-NL2SQL-with-prompting"
    sys.path.insert(0, str(repo))
    # Import with the original CLI configuration, without running its batch loop.
    sys.argv = [
        str(repo / "DIN-SQL.py"),
        "--dataset",
        str(source) + "/",
        "--output",
        str(OUTPUT / "din.txt"),
    ]
    spec = importlib.util.spec_from_file_location("din_original", repo / "DIN-SQL.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.spider_schema, module.spider_primary, module.spider_foreign = (
        module.creatiing_schema(str(source / "tables.json"))
    )
    original = module.generate

    def generation(config, prompt, **kwargs):
        # Determine stage from the actual caller, including retry calls.
        caller = sys._getframe(1).f_code.co_name
        stage = "Self-correction" if caller == "GPT4_debug" else active[0]
        return observed(stage, lambda text: original(config, text, **kwargs), prompt)

    active = ["Schema linking"]
    module.generate = generation
    for name, stage in [
        ("schema_linking_prompt_maker", "Schema linking"),
        ("classification_prompt_maker", "Classification"),
        ("easy_prompt_maker", "SQL generation"),
        ("medium_prompt_maker", "SQL generation"),
        ("hard_prompt_maker", "SQL generation"),
    ]:
        function = getattr(module, name)

        def maker(*args, _function=function, _stage=stage):
            active[0] = _stage
            return _function(*args)

        setattr(module, name, maker)
    return module.predict_one(row)


def mac(row, source):
    repo = WORKSPACE / "MAC-SQL"
    os.chdir(repo)
    sys.path.insert(0, str(repo))
    from core import agents, llm
    from core.chat_manager import ChatManager
    from core.const import SYSTEM_NAME

    active = ["Connection check"]
    original = llm.safe_call_llm

    def call(prompt, **kwargs):
        return observed(active[0], original, prompt, **kwargs)

    agents.LLM_API_FUC = call
    for cls in (agents.Selector, agents.Decomposer, agents.Refiner):
        original_talk = cls.talk

        @functools.wraps(original_talk)
        def talk(self, message, _talk=original_talk):
            active[0] = self.name
            emit("start", self.name + " · state", input=dict(message))
            result = _talk(self, message)
            emit("finish", self.name + " · state", output=dict(message))
            return result

        cls.talk = talk
    manager = ChatManager(
        data_path=os.path.relpath(source / "database", repo),
        tables_json_path=str(source / "tables.json"),
        log_path=str(OUTPUT / "mac_trace/log.txt"),
        dataset_name="spider",
        model_name=os.environ["LLM_MODEL"],
        lazy=True,
    )
    # No reference SQL is sent to the agents, including for custom questions.
    message = {
        "idx": 0,
        "db_id": row["db_id"],
        "query": row["question"],
        "evidence": "",
        "extracted_schema": {},
        "ground_truth": "",
        "difficulty": "unknown",
        "send_to": SYSTEM_NAME,
    }
    manager.start(message)
    return message.get("pred", "")


async def codex(row, source):
    from codex_mcp_sql import runner

    examples = OUTPUT / "codex-input.json"
    examples.write_text(json.dumps([row]), encoding="utf-8")
    args = argparse.Namespace(
        examples=examples,
        db_root=source / "database",
        output=OUTPUT / "codex",
        model=os.environ.get("CODEX_MODEL", "gpt-6-luna"),
        reasoning_effort="low",
        limit=1,
        workers=1,
        timeout=180,
        query_timeout=5,
        max_tool_calls=20,
        max_rows=100,
        codex=None,
        dry_run=False,
        resume=False,
    )
    original_write = runner.write_json

    def write(path, value):
        original_write(path, value)
        if path.name == "request.json":
            emit("start", "Codex turn", input=value)
        elif path.name == "turn.json":
            # The final public response and usage are sufficient; do not expose
            # reasoning items that may occur in the SDK's complete turn object.
            emit(
                "finish",
                "Codex turn",
                output={
                    k: value.get(k)
                    for k in ("status", "final_response", "usage", "error")
                },
            )

    runner.write_json = write
    seen = set()

    def drain():
        for path in (OUTPUT / "codex").glob("traces/*/tools.jsonl"):
            for index, line in enumerate(path.read_text().splitlines()):
                key = (str(path), index)
                if key in seen:
                    continue
                try:
                    record = json.loads(line)
                except json.JSONDecodeError:
                    continue
                seen.add(key)
                emit(
                    "error" if "error" in record else "tool",
                    record["tool"],
                    input=record.get("arguments"),
                    output=record.get("result", record.get("error")),
                    elapsed=record.get("elapsed_seconds"),
                )

    task = asyncio.create_task(runner.run(args))
    try:
        while not task.done():
            drain()
            await asyncio.sleep(0.15)
        await task
    finally:
        drain()
    result = json.loads((OUTPUT / "codex/traces/0000/result.json").read_text())
    if result["status"] != "completed":
        raise RuntimeError(result.get("error", "Codex failed"))
    return result["predicted_sql"]


def main():
    global OUTPUT, METHOD
    parser = argparse.ArgumentParser()
    parser.add_argument("--request", type=Path, required=True)
    parser.add_argument(
        "--method",
        choices=["din_sql", "mac_sql", "dail_sql", "codex_mcp"],
        required=True,
    )
    args = parser.parse_args()
    request = json.loads(args.request.read_text())
    OUTPUT, METHOD = args.request.parent, args.method
    row = {k: request[k] for k in ("question", "db_id")}
    row["example_id"] = "live_0000"
    source = ROOT / "downloads/spider_data"
    started = time.monotonic()
    emit("start", "Input", input=row)
    emit("finish", "Input", output=row)
    try:
        if METHOD == "codex_mcp":
            sql = asyncio.run(codex(row, source))
        elif METHOD == "dail_sql":
            from live_dail import run

            sql = run(row, source, OUTPUT, emit)
        else:
            sql = (din if METHOD == "din_sql" else mac)(row, source)
        if not sql or not sql.strip():
            raise ValueError("Method returned empty SQL")
        emit("result", "Final SQL", output=sql, elapsed=time.monotonic() - started)
    except Exception as error:  # noqa: BLE001 - original runner failures need a terminal event
        emit(
            "failed",
            "Run failed",
            output=str(error),
            elapsed=time.monotonic() - started,
        )
        traceback.print_exc()
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
